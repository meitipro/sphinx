        "---",
        "",
        "{/* Generated by scripts/gen_docs.py from tests/vectors.json. Do not edit by hand. */}",
        "",
        "Locks and seals are SHA-256 over UTF-8 text joined with a bar, `|`, as lower-case hex. The contract computes "
        "them with Python's `hashlib`, the site with the browser's SubtleCrypto, and both are tested against the same "
        "vectors (`tests/vectors.json`): `tests/test_static.py` checks the contract and runs `web/scripts/check-vectors.mjs` "
        "for the site.",
        "",
        "```text",
        "lock = sha256(answer + \"|\" + notes + \"|\" + salt)",
        "seal = sha256(answer + \"|\" + salt + \"|\" + lower_case(address))",
