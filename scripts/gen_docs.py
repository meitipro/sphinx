# -- code samples copied from files that run -----------------------------------------
INCLUDE_OPEN = "{/* include: "
INCLUDE_CLOSE = "{/* end include */}"
LANGS = {".mjs": "js", ".js": "js", ".ts": "ts", ".py": "python", ".json": "json"}
GENERATED = ("reference/contract.mdx", "reference/errors.mdx", "more/judge-prompt.mdx", "more/evaluation.mdx", "reference/addresses.mdx")


def expand(text: str) -> str:
    """Replace every include block's body with the file it names, fenced."""
    if INCLUDE_OPEN not in text:
        return text
    parts = []
    rest = text
    while INCLUDE_OPEN in rest:
        before, _, after = rest.partition(INCLUDE_OPEN)
        path_text, _, after = after.partition(" */}")
        _, _, after = after.partition(INCLUDE_CLOSE)
        source = ROOT / path_text.strip()
        code = source.read_text(encoding="utf-8").rstrip("\n")
        lang = LANGS.get(source.suffix, "")
        parts.append(before + INCLUDE_OPEN + path_text + " */}\n```" + lang + ' title="' + path_text.strip() + '"\n' + code + "\n```\n" + INCLUDE_CLOSE)
        rest = after
    parts.append(rest)
    return "".join(parts)


def synced_includes() -> dict[pathlib.Path, str]:
    """
    Every `{/* include: path */}` ... `{/* end include */}` block in the docs is
    replaced by the file at <repo>/<path>, fenced. A sample in the docs is then
    the code in the repository, which is the code that was run.
    """
    out: dict[pathlib.Path, str] = {}
    generated = {DOCS / g for g in GENERATED} | {DOCS / "reference" / "hashing.mdx"}
    for page in sorted(DOCS.rglob("*.mdx")):
        if page in generated:
            continue
        text = page.read_text(encoding="utf-8")
        if INCLUDE_OPEN in text:
            out[page] = expand(text)
    return out


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    files = build()
    hashing = DOCS / "reference" / "hashing.mdx"
    files[hashing] = expand(files[hashing])
    for path, text in files.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path.relative_to(ROOT).as_posix())
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if check:
        if stale:
            print("stale generated files, run python scripts/gen_docs.py:\n  " + "\n  ".join(stale))
            return 1
        print("generated files match the contract")
        return 0
    print("wrote " + (", ".join(stale) if stale else "nothing, all current"))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
